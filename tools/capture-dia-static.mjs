import { chromium } from "playwright";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2 });
page.on("pageerror", (e) => console.log("PAGEERROR:", e.message));
await page.goto("http://localhost:8479", { waitUntil: "networkidle" });
await page.waitForTimeout(800);
await page.screenshot({ path: ".previews/dia-static-landing.png" });
await page.click("[data-enter]");
await page.waitForTimeout(1600);
await page.screenshot({ path: ".previews/dia-static-inside.png", fullPage: false });
await page.click('[data-tx="3"]');
await page.waitForTimeout(500);
await page.screenshot({ path: ".previews/dia-static-modal.png" });
console.log("saved 3");
await browser.close();
